class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem('topraklar_lang') || localStorage.getItem('vanguard_lang') || 'tr';
    this.init();
  }

  init() {
    document.addEventListener('DOMContentLoaded', () => {
      this.bindEvents();
      this.setLanguage(this.currentLang);
    });
  }

  bindEvents() {
    const langBtn = document.getElementById('currentLangBtn');
    const langDropdown = document.getElementById('langDropdownMenu');

    if (langBtn && langDropdown) {
      langBtn.addEventListener('click', (e) => {
        e.preventDefault();
        e.stopPropagation();
        langDropdown.classList.toggle('show');
      });

      document.addEventListener('click', () => {
        langDropdown.classList.remove('show');
      });
    }

    // Attach to all language switcher triggers across the page
    document.querySelectorAll('[data-lang]').forEach(opt => {
      opt.addEventListener('click', (e) => {
        e.preventDefault();
        const targetLang = opt.getAttribute('data-lang');
        this.setLanguage(targetLang);
        if (langDropdown) langDropdown.classList.remove('show');
      });
    });
  }

  setLanguage(lang) {
    if (!translations[lang]) lang = 'tr';
    this.currentLang = lang;
    localStorage.setItem('topraklar_lang', lang);
    localStorage.setItem('vanguard_lang', lang);
    this.applyTranslations(lang);
    if (window.lucide && typeof window.lucide.createIcons === 'function') {
      window.lucide.createIcons();
    }

    // Update active class on dropdown and any flag selectors
    document.querySelectorAll('[data-lang]').forEach(opt => {
      if (opt.getAttribute('data-lang') === lang) {
        opt.classList.add('active');
      } else {
        opt.classList.remove('active');
      }
    });

    // Update current lang button display with SVG flag image
    const isSubDir = window.location.pathname.includes('/services/');
    const flagPrefix = isSubDir ? '../assets/flags/' : 'assets/flags/';
    const currentFlag = document.getElementById('currentLangFlag');
    if (currentFlag) {
      if (currentFlag.tagName === 'IMG') {
        currentFlag.src = flagPrefix + lang + '.svg';
        currentFlag.alt = lang.toUpperCase();
      } else {
        currentFlag.innerHTML = `<img src="${flagPrefix + lang}.svg" alt="${lang.toUpperCase()}" class="flag-img">`;
      }
    }

    const currentCode = document.getElementById('currentLangCode');
    if (currentCode) {
      currentCode.textContent = '';
      currentCode.style.display = 'none';
    }

    // Set html lang and direction for RTL languages like Arabic
    document.documentElement.lang = lang;
    if (lang === 'ar') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }

  applyTranslations(lang) {
    const dict = translations[lang] || translations.tr;

    // 1. Text elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = dict[key];
        } else if (el.querySelector('i[data-lucide], svg')) {
          // If element contains an icon, preserve the icon and update text or child span
          const span = el.querySelector('span:not([data-i18n])');
          if (span) {
            span.textContent = dict[key];
          } else {
            const icon = el.querySelector('i[data-lucide], svg');
            let textNode = null;
            for (let n of el.childNodes) {
              if (n.nodeType === Node.TEXT_NODE && n.textContent.trim().length > 0) {
                textNode = n;
                break;
              }
            }
            if (textNode) {
              textNode.textContent = ' ' + dict[key] + ' ';
            } else {
              const iconHtml = icon.outerHTML;
              el.innerHTML = iconHtml + ' ' + dict[key];
            }
          }
        } else {
          el.textContent = dict[key];
        }
      }
    });

    // 2. Explicit Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.placeholder = dict[key];
      }
    });

    // 3. Titles / tooltips
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.title = dict[key];
      }
    });
  }

  translate(key) {
    const dict = translations[this.currentLang] || translations.tr;
    return dict[key] || key;
  }
}

// Global instance
window.vanguardI18n = new I18nManager();
window.vanguardT = (key) => window.vanguardI18n.translate(key);
